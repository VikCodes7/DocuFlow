//! DocuFlow app layer: Tauri setup, IPC commands, jobs, access control,
//! storage and logging. All processing lives in `docuflow-core` (AD-1).

pub mod access;
pub mod commands;
pub mod jobs;
pub mod logging;
pub mod output;
pub mod storage;

use std::path::PathBuf;

use specta_typescript::Typescript;
use tauri::{DragDropEvent, Manager, WindowEvent};
use tauri_specta::{Builder, ErrorHandlingMode, Event, collect_commands, collect_events};

use crate::access::AllowedPaths;
use crate::commands::FilesDropped;
use crate::jobs::JobManager;
use crate::storage::History;

/// Folder (inside the app cache) that previews are written to. It is the
/// only location the asset protocol may serve (see `tauri.conf.json`).
pub const PREVIEW_DIR: &str = "previews";

/// Every IPC command and event. Adding a command here is what makes it
/// callable and generates its TypeScript binding.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::app_info,
            commands::pick_input_files,
            commands::pick_output_folder,
            commands::cancel_job,
            commands::list_history,
            commands::clear_history,
            commands::open_log_folder,
        ])
        .events(collect_events![FilesDropped])
        // Commands resolve to `{ status: "ok", data } | { status: "error", error: CoreError }`.
        .error_handling(ErrorHandlingMode::Result)
}

pub fn bindings_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/bindings/index.ts")
}

pub fn export_bindings(builder: &Builder<tauri::Wry>) {
    builder
        .export(
            Typescript::default().header("// Generated by tauri-specta from src-tauri. Do not edit.\n/* eslint-disable */\n// @ts-nocheck"),
            bindings_path(),
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();

    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .manage(AllowedPaths::default())
        .manage(JobManager::default())
        .setup(move |app| {
            builder.mount_events(app);

            if let Some(guard) = logging::init(&app.path().app_log_dir()?) {
                app.manage(guard);
            }
            tracing::info!(version = %app.package_info().version, "DocuFlow starting");

            let data_dir = app.path().app_data_dir()?;
            std::fs::create_dir_all(&data_dir)?;
            app.manage(History::open(&data_dir.join("history.sqlite3"))?);

            // Previews never outlive a session.
            let previews = app.path().app_cache_dir()?.join(PREVIEW_DIR);
            let _ = std::fs::remove_dir_all(&previews);
            std::fs::create_dir_all(&previews)?;

            Ok(())
        })
        .on_window_event(|window, event| {
            if let WindowEvent::DragDrop(DragDropEvent::Drop { paths, .. }) = event {
                let files =
                    commands::register_files(&window.state::<AllowedPaths>(), paths.clone());
                if !files.is_empty() {
                    let _ = FilesDropped { files }.emit(window.app_handle());
                }
            }
        })
        .run(tauri::generate_context!())
        .expect("error while running DocuFlow");
}

#[cfg(test)]
mod tests {
    /// Regenerates `src/bindings/index.ts`. CI runs this and fails if the
    /// committed file changed, so bindings can't drift from Rust (AD-2).
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::specta_builder());
        assert!(super::bindings_path().exists());
    }
}
